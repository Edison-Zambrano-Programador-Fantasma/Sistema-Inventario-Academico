    private void jButton_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_guardarActionPerformed

        String tipo_usuario = jComboBox_tipo_usuario.getSelectedItem().toString();
        String nombres = txt_nombres.getText().trim();
        String apellidos = txt_apellidos.getText().trim();
        String correo = txt_correo.getText().trim();
        String clave = txt_clave.getText().trim();
        String estado = jComboBox_estado.getSelectedItem().toString();
        //validamos campos vacios
        if (nombres.isEmpty() || apellidos.isEmpty() || correo.isEmpty()
                || clave.isEmpty() || tipo_usuario.equals("Seleccione Tipo Usuario:")) {
            JOptionPane.showMessageDialog(null, "¡Complete todos los campos!");
        } else {
            UsuarioController usuarioController = new UsuarioController();

            Usuario usuario = new Usuario();
            TipoUsuario tipo = new TipoUsuario();

            usuario.setIdUsuario(0);
//            usuario.setIdTipoUsuario(1);
            tipo.setIdTipoUsuario(obtenerIdTipoUsuario());
            usuario.setNombres(nombres);
            usuario.setApellidos(apellidos);
            usuario.setCorreo(correo);
            usuario.setClave(clave);
            usuario.setEstado(estado);
            //metodo guardar
            if (usuarioController.guardar(usuario, tipo)) {
                JOptionPane.showMessageDialog(null, "¡Usuario Guardado!");
                //vaciar los campos
                txt_nombres.setText("");
                txt_apellidos.setText("");
                txt_correo.setText("");
                txt_clave.setText("");
                jComboBox_estado.setSelectedItem("Activo");
                jComboBox_estado.setSelectedItem("Seleccione Tipo Usuario:");

                //Cargar la tabla para actualizar los registros
                this.cargarTablaUsuarios();
//                        System.out.println("Helloooo!!!!!");
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(null, "¡Error al Guardar!");

            }
        }
    }//GEN-LAST:event_jButton_guardarActionPerformed


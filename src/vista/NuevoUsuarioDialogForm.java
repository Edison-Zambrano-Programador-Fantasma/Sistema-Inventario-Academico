    private void cargarTablaUsuarios() {

        // Crear el controlador y obtener los estudiantes
        UsuarioController controller = new UsuarioController();
        ArrayList<Usuario> listaUsuarios = controller.obtenerUsuarios();

        // Crear las columnas de la tabla
        String[] columnas = {"ID", "Tipo Usuario", "Nombres", "Correo", "Clave", "Estado"};

        // Crear el modelo de la tabla y agregar los datos del ArrayList
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(columnas);

        InterUsuario.jTable_usuarios = new JTable(model);
        InterUsuario.jScrollPane1.setViewportView(InterUsuario.jTable_usuarios);

        this.CargarEstilos();

        // Configurar el ancho de las columnas
        jTable_usuarios.getColumnModel().getColumn(0).setPreferredWidth(40);  // ID
        jTable_usuarios.getColumnModel().getColumn(1).setPreferredWidth(300); // Tipo de Usuario
        jTable_usuarios.getColumnModel().getColumn(2).setPreferredWidth(350); // Nombres
        jTable_usuarios.getColumnModel().getColumn(3).setPreferredWidth(300); // Correo
        jTable_usuarios.getColumnModel().getColumn(4).setPreferredWidth(200); // Clave
        jTable_usuarios.getColumnModel().getColumn(5).setPreferredWidth(150); // Estado

        // Llenar el modelo con los datos del ArrayList<Usuarios>
        for (Usuario usuario : listaUsuarios) {
            Object[] fila = {
                usuario.getIdUsuario(),
                usuario.getTipo_usuario().getDescripcion(),
                usuario.getNombres() + " " + usuario.getApellidos(),
                usuario.getCorreo(),
                usuario.getClave(),
                usuario.getEstado()
            };
            model.addRow(fila);
        }

        //evento para obtener campo al cual el usuario da click
        //y obtener la interfaz que mostrara la informacion general
        jTable_usuarios.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int fila_point = jTable_usuarios.rowAtPoint(e.getPoint());
                int columna_point = 0;

                if (fila_point > -1) {
                    idUsuario = (int) model.getValueAt(fila_point, columna_point);
                    controller.enviarDatosAModal(idUsuario);//metodo
                }
            }
        });
    }

    /**
     * Metodo para cargar los tipos de usuarios
     */
    private void cargarComboTipoUsuario() {
        java.sql.Connection cn = Conexion.conectar();
        String sql = "select * from tipo_usuario";
        Statement st;
        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            jComboBox_tipo_usuario.removeAllItems();
            jComboBox_tipo_usuario.addItem("Seleccione Tipo Usuario:");
            while (rs.next()) {
                jComboBox_tipo_usuario.addItem(rs.getString("descripcion"));
            }
        } catch (SQLException e) {
            System.out.println("Error al cargar tipos de usuarios");
        }
    }

    /**
     * Metodo para obtener id del tipo de usuario
     */
    private int obtenerIdTipoUsuario() {
        String sql = "select * from tipo_usuario where descripcion = '" + jComboBox_tipo_usuario.getSelectedItem() + "'";
        Statement st;
        try {
            java.sql.Connection cn = Conexion.conectar();
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            while (rs.next()) {
                idTipoUsuario = rs.getInt("id_tipo_usuario");
            }
        } catch (SQLException e) {
            System.out.println("Error al obener id tipo de usuario");
        }
        return idTipoUsuario;
    }


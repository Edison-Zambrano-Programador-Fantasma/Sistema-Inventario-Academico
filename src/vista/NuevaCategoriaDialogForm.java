    private void CargarEstilos() {
        // Estilos del encabezado del jtable
        JTableHeader header = InterCategoria.jTable_categorias.getTableHeader();
        header.setFont(new Font("Serif", Font.BOLD, 18));  // Fuente negrita para el encabezado
        header.setBackground(Color.WHITE);  // Fondo del encabezado
        header.setForeground(new Color(11, 34, 97));  // Color de Texto del encabezado
        // Cambiar la fuente de la tabla
        InterCategoria.jTable_categorias.setFont(new Font("Serif", Font.PLAIN, 20));
        // Cambiar el color de fondo de las celdas seleccionadas
        InterCategoria.jTable_categorias.setSelectionBackground(new Color(0, 255, 255));
        // Cambiar el color del texto de las celdas seleccionadas
        InterCategoria.jTable_categorias.setSelectionForeground(new Color(30, 119, 37));
        // Cambiar el color de la cuadrícula
        InterCategoria.jTable_categorias.setGridColor(Color.BLACK);
        // Ajusta la altura de las filas de la tabla
        InterCategoria.jTable_categorias.setRowHeight(30);
    }

    private void cargarTablaCategorias() {

        // Crear el controlador y obtener los estudiantes
        CategoriaController controller = new CategoriaController();
        ArrayList<Categoria> listaCategorias = controller.obtenerCategorias();

        // Crear las columnas de la tabla
        String[] columnas = {"ID", "Nombres", "Descripcion", "Estado"};

        // Crear el modelo de la tabla y agregar los datos del ArrayList
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(columnas);

        InterCategoria.jTable_categorias = new JTable(model);
        InterCategoria.jScrollPane1.setViewportView(InterCategoria.jTable_categorias);

        this.CargarEstilos();

        // Configurar el ancho de las columnas
        jTable_categorias.getColumnModel().getColumn(0).setPreferredWidth(40);  // ID
        jTable_categorias.getColumnModel().getColumn(1).setPreferredWidth(350); // Nombres
        jTable_categorias.getColumnModel().getColumn(2).setPreferredWidth(600); // Descripcion
        jTable_categorias.getColumnModel().getColumn(3).setPreferredWidth(250); // Estado

        // Llenar el modelo con los datos del ArrayList<Usuarios>
        for (Categoria categoria : listaCategorias) {
            Object[] fila = {
                categoria.getIdCategoria(),
                categoria.getNombre(),
                categoria.getDescripcion(),
                categoria.getEstado()
            };
            model.addRow(fila);
        }

        //evento para obtener campo al cual el usuario da click
        //y obtener la interfaz que mostrara la informacion general
        jTable_categorias.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int fila_point = jTable_categorias.rowAtPoint(e.getPoint());
                int columna_point = 0;

                if (fila_point > -1) {
                    idCategoria = (int) model.getValueAt(fila_point, columna_point);
                    controller.enviarDatosAModal(idCategoria);//metodo
                }
            }
        });
    }

    private void jButton_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_guardarActionPerformed

        String nombres = txt_nombre.getText().trim();
        String descripcion = txt_descripcion.getText().trim();
        String estado = jComboBox_estado.getSelectedItem().toString();
        //validamos campos vacios
        if (nombres.isEmpty() || descripcion.isEmpty()) {
            JOptionPane.showMessageDialog(null, "¡Complete todos los campos!");
        } else {
            CategoriaController categoriaController = new CategoriaController();

            Categoria categoria = new Categoria();
            categoria.setIdCategoria(0);
            categoria.setNombre(nombres);
            categoria.setDescripcion(descripcion);
            categoria.setEstado(estado);
            //metodo guardar
            if (categoriaController.guardar(categoria)) {
                JOptionPane.showMessageDialog(null, "¡Categoria Guardada!");
                //vaciar los campos
                txt_nombre.setText("");
                txt_descripcion.setText("");
                jComboBox_estado.setSelectedItem("Activo");

                //Cargar la tabla para actualizar los registros
                this.cargarTablaCategorias();
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(null, "¡Error al Guardar!");

            }
        }
    }//GEN-LAST:event_jButton_guardarActionPerformed


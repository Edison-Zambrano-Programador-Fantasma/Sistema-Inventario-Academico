    //metodo para validar permisos de Usuario
    private void validarPermisos() {

        int rol = Sesion.usuarioLogueado.getTipo_usuario().getIdTipoUsuario();

        switch (rol) {

            case 1: // Administrador

                break;

            case 2: // Operador

                jMenu_usuario.setVisible(false);

                break;

            case 3: // Invitado

                jMenu_usuario.setVisible(false);
                jMenu_equipos.setVisible(false);
                jMenu_categorias.setVisible(false);
                jMenu_ubicacion.setVisible(false);

                break;
        }
    }

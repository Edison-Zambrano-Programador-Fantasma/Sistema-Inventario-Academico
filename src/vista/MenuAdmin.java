    private void jMenuItem_usuariosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem_usuariosActionPerformed
        InterUsuario inter = new InterUsuario();
        jDesktopPane_menu.add(inter);
        // Calcular el centro
        int x = (jDesktopPane_menu.getWidth() - inter.getWidth()) / 2;
        int y = (jDesktopPane_menu.getHeight() - inter.getHeight()) / 2;

        // Establecer la ubicación centrada
        inter.setLocation(x, y);
        inter.setVisible(true);
    }//GEN-LAST:event_jMenuItem_usuariosActionPerformed


    private void actualizarStatusEquipo(int idEquipo, String status) {

        String sql = "UPDATE equipo SET status = ? WHERE id_equipo = ?";

        try (Connection cn = Conexion.conectar(); PreparedStatement pst = cn.prepareStatement(sql)) {

            pst.setString(1, status);
            pst.setInt(2, idEquipo);

            pst.executeUpdate();

        } catch (SQLException e) {
            System.out.println(
                    "Error al actualizar status del equipo: "
                    + e.getMessage());
        }
    }

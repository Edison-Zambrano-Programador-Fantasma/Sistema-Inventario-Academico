    private void cargarTablaMantenimientos() {

        // Crear el controlador 
        MantenimientoController controller = new MantenimientoController();
        ArrayList<Mantenimiento> listaMantenimientos = controller.obtenerMantenimientos();

        // Crear las columnas de la tabla
        String[] columnas = {"ID", "Codigo Equipo", "Equipo", "Fecha Inicio", "Fecha Fin", "Descripcion", "Status", "Estado"};

        // Crear el modelo de la tabla y agregar los datos del ArrayList
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(columnas);

        InterMantenimiento.jTable_mantenimientos = new JTable(model);
        InterMantenimiento.jScrollPane1.setViewportView(InterMantenimiento.jTable_mantenimientos);

        this.CargarEstilos();

        // Configurar el ancho de las columnas
        jTable_mantenimientos.getColumnModel().getColumn(0).setPreferredWidth(40);  // ID
        jTable_mantenimientos.getColumnModel().getColumn(1).setPreferredWidth(200); // Codigo Equipo
        jTable_mantenimientos.getColumnModel().getColumn(2).setPreferredWidth(200); // Equipo
        jTable_mantenimientos.getColumnModel().getColumn(3).setPreferredWidth(200); // Fecha Inicio
        jTable_mantenimientos.getColumnModel().getColumn(4).setPreferredWidth(200); // Fecha Fin
        jTable_mantenimientos.getColumnModel().getColumn(5).setPreferredWidth(400); // Descripcion
        jTable_mantenimientos.getColumnModel().getColumn(6).setPreferredWidth(200); // Status
        jTable_mantenimientos.getColumnModel().getColumn(7).setPreferredWidth(200); // estado

        // Llenar el modelo con los datos del ArrayList<Equipo>
        for (Mantenimiento mantenimiento : listaMantenimientos) {
            Object[] fila = {
                mantenimiento.getIdMantenimiento(),
                mantenimiento.getEquipo().getCodigo(),
                mantenimiento.getEquipo().getNombre(),
                mantenimiento.getFechaInicio(),
                mantenimiento.getFechaFin(),
                mantenimiento.getDescripcion(),
                mantenimiento.getEquipo().getStatus(),
                mantenimiento.getEstado()
            };
            model.addRow(fila);
        }

        //evento para obtener campo al cual el usuario da click
        //y obtener la interfaz que mostrara la informacion general
        jTable_mantenimientos.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int fila_point = jTable_mantenimientos.rowAtPoint(e.getPoint());
                int columna_point = 0;

                if (fila_point > -1) {
                    idMantenimiento = (int) model.getValueAt(fila_point, columna_point);
                    controller.enviarDatosAModal(idMantenimiento);//metodo
                }
            }
        });
    }


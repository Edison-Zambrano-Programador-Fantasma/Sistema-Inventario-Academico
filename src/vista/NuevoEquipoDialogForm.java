    private void jButton_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_guardarActionPerformed

        String categoria = jComboBox_categorias.getSelectedItem().toString();
        String ubicacion = jComboBox_ubicaciones.getSelectedItem().toString();
        String codigo = txt_codigo.getText().trim();
        String nombre = txt_nombre.getText().trim();
        String marca = txt_marca.getText().trim();
        String modelo = txt_modelo.getText().trim();
        String status = txt_status.getText().trim();
        String estado = jComboBox_estado.getSelectedItem().toString();
        //validamos campos vacios
        if (codigo.isEmpty() || nombre.isEmpty() || marca.isEmpty()
                || modelo.isEmpty() || status.isEmpty() || categoria.equals("Seleccione Categoria:") || ubicacion.equals("Seleccione Ubicacion:")) {
            JOptionPane.showMessageDialog(null, "¡Complete todos los campos!");
        } else {
            EquipoController equipoController = new EquipoController();

            Equipo equipo = new Equipo();
            Categoria categoriaObjeto = new Categoria();
            Ubicacion ubicacionObjeto = new Ubicacion();

            equipo.setIdEquipo(0);
            //--
            categoriaObjeto.setIdCategoria(jComboBox_categorias.getSelectedIndex());
            equipo.setCategoria(categoriaObjeto);
            ubicacionObjeto.setIdUbicacion(jComboBox_ubicaciones.getSelectedIndex());
            equipo.setUbicacion(ubicacionObjeto);
            //--
            equipo.setCodigo(codigo);
            equipo.setNombre(nombre);
            equipo.setMarca(marca);
            equipo.setModelo(modelo);
            equipo.setStatus(status);
            equipo.setEstado(estado);
            //metodo guardar
            if (equipoController.guardar(equipo)) {
                JOptionPane.showMessageDialog(null, "¡Equipo Guardado!");
                //vaciar los campos
                jComboBox_categorias.setSelectedItem("Seleccione Categoria:");
                jComboBox_ubicaciones.setSelectedItem("Seleccione Ubicacion:");
                txt_codigo.setText("");
                txt_nombre.setText("");
                txt_marca.setText("");
                txt_modelo.setText("");
                txt_status.setText("");
                jComboBox_estado.setSelectedItem("Activo");

                //Cargar la tabla para actualizar los registros
                this.cargarTablaEquipos();
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(null, "¡Error al Guardar!");

            }
        }
    }//GEN-LAST:event_jButton_guardarActionPerformed


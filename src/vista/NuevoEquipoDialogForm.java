    private void cargarTablaEquipos() {

        // Crear el controlador y obtener los estudiantes
        EquipoController controller = new EquipoController();
        ArrayList<Equipo> listaEquipos = controller.obtenerEquipos();

        // Crear las columnas de la tabla
        String[] columnas = {"ID", "Categoria", "Ubicacion", "Codigo", "Nombre", "Marca", "Modelo", "Status", "Estado"};

        // Crear el modelo de la tabla y agregar los datos del ArrayList
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(columnas);

        InterEquipo.jTable_equipos = new JTable(model);
        InterEquipo.jScrollPane1.setViewportView(InterEquipo.jTable_equipos);

        this.CargarEstilos();

        // Configurar el ancho de las columnas
        jTable_equipos.getColumnModel().getColumn(0).setPreferredWidth(40);  // ID
        jTable_equipos.getColumnModel().getColumn(1).setPreferredWidth(200); // Categoria
        jTable_equipos.getColumnModel().getColumn(2).setPreferredWidth(200); // Ubicacion
        jTable_equipos.getColumnModel().getColumn(3).setPreferredWidth(150); // Codigo
        jTable_equipos.getColumnModel().getColumn(4).setPreferredWidth(300); // Nombre
        jTable_equipos.getColumnModel().getColumn(5).setPreferredWidth(150); // Marca
        jTable_equipos.getColumnModel().getColumn(6).setPreferredWidth(200); // Modelo
        jTable_equipos.getColumnModel().getColumn(7).setPreferredWidth(200); // status
        jTable_equipos.getColumnModel().getColumn(8).setPreferredWidth(200); // estado

        // Llenar el modelo con los datos del ArrayList<Equipo>
        for (Equipo equipo : listaEquipos) {
            Object[] fila = {
                equipo.getIdEquipo(),
                equipo.getCategoria().getDescripcion(),
                equipo.getUbicacion().getDescripcion(),
                equipo.getCodigo(),
                equipo.getNombre(),
                equipo.getMarca(),
                equipo.getModelo(),
                equipo.getStatus(),
                equipo.getEstado()
            };
            model.addRow(fila);
        }

        //evento para obtener campo al cual el usuario da click
        //y obtener la interfaz que mostrara la informacion general
        jTable_equipos.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int fila_point = jTable_equipos.rowAtPoint(e.getPoint());
                int columna_point = 0;

                if (fila_point > -1) {
                    idEquipo = (int) model.getValueAt(fila_point, columna_point);
                    controller.enviarDatosAModal(idEquipo);//metodo
                }
            }
        });
    }

    /**
     * Metodo para cargar las categorias
     */
    private void cargarComboCategorias() {
        java.sql.Connection cn = Conexion.conectar();
        String sql = "select * from categoria";
        Statement st;
        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            jComboBox_categorias.removeAllItems();
            jComboBox_categorias.addItem("Seleccione Categoria:");
            while (rs.next()) {
                jComboBox_categorias.addItem(rs.getString("nombre"));
            }
        } catch (SQLException e) {
            System.out.println("Error al cargar las categorias");
        }
    }

    /**
     * Metodo para obtener id de la categoria
     */
    private int obtenerIdCategoria() {
        String sql = "select * from categoria where nombre = '" + jComboBox_categorias.getSelectedItem() + "'";
        Statement st;
        try {
            java.sql.Connection cn = Conexion.conectar();
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            while (rs.next()) {
                idCategoria = rs.getInt("id_categoria");
            }
        } catch (SQLException e) {
            System.out.println("Error al obener id de la categoria");
        }
        return idCategoria;
    }

